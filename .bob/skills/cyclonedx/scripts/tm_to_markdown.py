#!/usr/bin/env python3
"""Write a threat-model BOM (TM-BOM) as human-readable Markdown tables.

A TM-BOM is CycloneDX 2.0 JSON, written for tools. This script renders it for
people, in the shape of the working group's threat table
(subgroups/use-cases-and-threat-models/use_cases/code_assistant/threats/):

  Threats    one row per threat: the threat statement, STRIDE and MAESTRO
             categories, where it is located (affected elements by zone),
             the actor, NIST SP 800-30 source, event and impact, the
             catalogue items it realizes, MITRE ATT&CK and ATLAS techniques,
             whether it is AI specific, CAPEC and CWE with their rationales,
             the mitigating controls and the risk.
  Controls   one row per control, with the NIST SP 800-53 and CSA AICM
             requirements it satisfies and the threats it mitigates.
  Not applicable
             every catalogue sweep decision that an item does not apply,
             with its reason, so reviewers can check the reasons.

The page is generated: change the TM-BOM and run this again, never edit the
page by hand. The output depends only on the TM-BOM, so regenerating an
unchanged TM-BOM gives an identical file.

Usage:
  tm_to_markdown.py TM.json [-o OUT.md]
      Default output: TM.json with '.json' replaced by '.threats.md', next to
      the TM-BOM. '-o -' prints to stdout. An existing file is replaced only
      if this tool wrote it.

"AI specific?" is Yes when the threat cites a MITRE ATLAS technique or an
item of the OWASP Top 10 for LLM Applications or for Agentic Applications.
A MAESTRO category alone does not make a threat AI specific, because MAESTRO
is applied to every threat on an AI or agentic element.

Standard library only.
"""

import argparse
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import tm_checks  # noqa: E402

GENERATOR = "Generated by tm_to_markdown.py"
AI_CATALOGUES = ("owasp-llm-top10", "owasp-agentic-top10")
STRUCTURAL = ("aggregates", "composes", "contains")
CAPEC_URL = "https://capec.mitre.org/data/definitions/{}.html"


# ------------------------------------------------------------------ text

def cell(text):
    """Escape BOM text for one Markdown table cell."""
    text = str(text if text is not None else "")
    text = text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    text = text.replace("|", "\\|")
    return re.sub(r"\s*\r?\n\s*", "<br>", text.strip())


def link(text, url):
    text = cell(text).replace("[", "\\[").replace("]", "\\]")
    return f"[{text}]({url})" if url else text


def code(ref):
    return f"`{str(ref).replace('`', '')}`"


def words(value):
    """'information-disclosure' -> 'Information disclosure'."""
    value = str(value).replace("-", " ").replace("_", " ")
    return value[:1].upper() + value[1:]


def lines(items):
    return "<br>".join(i for i in items if i) or "-"


def props(obj, name):
    return [v for n, v in tm_checks._props(obj) if n == name]


# ------------------------------------------------------------------ lookups

class Catalogues:
    """ID -> (title, url) for each catalogue in reference/catalogues/."""

    def __init__(self, refs):
        self.meta = refs.catalogue_meta
        self.items = {}
        for key, meta in self.meta.items():
            path = os.path.join(tm_checks.CATALOGUE_DIR, meta.get("file", ""))
            if os.path.exists(path):
                self.items[key] = {r["id"]: (r.get("title", ""), r.get("url", ""))
                                   for r in tm_checks._read_csv(path)}

    def item(self, key, ident, with_catalogue=True):
        title, url = self.items.get(key, {}).get(ident, ("", ""))
        text = link(f"{ident} {title}".strip(), url)
        name = (self.meta.get(key) or {}).get("name", key)
        return f"{cell(name)}: {text}" if with_catalogue else text

    def technique(self, ident):
        key = "mitre-atlas" if ident.startswith("AML.") else "mitre-attack-enterprise"
        return key, self.item(key, ident, with_catalogue=False)


class Index:
    """Names, zones and parties of the elements in a TM-BOM."""

    def __init__(self, doc):
        self.doc = doc
        defs = doc.get("definitions") or {}
        bp = (doc.get("blueprints") or [{}])[0]
        self.bp = bp
        self.names, self.kinds = {}, {}
        self._walk(doc, None)
        self.zones = {z["refId"] for z in bp.get("zones") or [] if "refId" in z}
        self.parties = {p["refId"]: p for p in defs.get("parties") or [] if "refId" in p}
        self.actors = {}
        for a in bp.get("actors") or []:
            party = a.get("party")
            if isinstance(party, dict) and "refId" in party:
                self.parties.setdefault(party["refId"], party)
            if "refId" in a:
                self.actors[a["refId"]] = a
        self.parent, self.realized_by = {}, {}
        for rel in bp.get("relationships") or []:
            for kind in STRUCTURAL:
                for child in rel.get(kind) or []:
                    self.parent.setdefault(child, rel.get("ref"))
            for actor in rel.get("realizes") or []:
                self.realized_by.setdefault(actor, rel.get("ref"))
        self.requirements = {}
        for std in defs.get("standards") or []:
            for req in std.get("requirements") or []:
                if "refId" in req:
                    self.requirements[req["refId"]] = (std.get("name", ""), req)

    def _walk(self, inst, key):
        if isinstance(inst, dict):
            rid = inst.get("refId")
            if isinstance(rid, str) and rid not in self.names and inst.get("name"):
                self.names[rid] = inst["name"]
                self.kinds[rid] = key
            for k, v in inst.items():
                self._walk(v, k)
        elif isinstance(inst, list):
            for v in inst:
                self._walk(v, key)

    def party_label(self, ref):
        party = self.parties.get(ref)
        if party is None and ref in self.actors:
            party = self.actors[ref].get("party")
        if not isinstance(party, dict):
            return code(ref)
        for shape in ("organization", "person", "system"):
            if isinstance(party.get(shape), dict) and party[shape].get("name"):
                return cell(party[shape]["name"])
        persona = party.get("persona") or {}
        if persona.get("label"):
            return cell(persona["label"])
        if persona.get("archetype"):
            return cell(words(persona["archetype"]))
        roles = [r.get("role") for r in party.get("roles") or [] if isinstance(r, dict) and r.get("role")]
        return cell(words(roles[0])) if roles else code(ref)

    def name(self, ref):
        if ref in self.names:
            return cell(self.names[ref])
        if ref in self.actors:
            comp = self.realized_by.get(ref)
            return cell(self.names[comp]) if comp in self.names else self.party_label(ref)
        return code(ref)

    def zone(self, ref):
        """The zone an element sits in, following structural relationships up to a zone."""
        if ref in self.actors:
            if self.actors[ref].get("zone"):
                return self.actors[ref]["zone"]
            ref = self.realized_by.get(ref, ref)
        seen = set()
        while ref and ref not in seen:
            seen.add(ref)
            ref = self.parent.get(ref)
            if ref in self.zones:
                return ref
        return None

    def located_in(self, refs):
        """Affected elements grouped by zone, then flows and boundaries."""
        by_zone, other = {}, []
        for ref in refs:
            kind = self.kinds.get(ref)
            if kind in ("flows", "boundaries"):
                other.append(f"{'Flow' if kind == 'flows' else 'Boundary'}: {self.name(ref)}")
            elif ref in self.zones:
                by_zone.setdefault(ref, [])
            else:
                by_zone.setdefault(self.zone(ref), []).append(self.name(ref))
        out = []
        for zone, names in by_zone.items():
            label = self.name(zone) if zone else ""
            body = ", ".join(names)
            out.append(f"{label}: {body}" if label and body else label or body)
        return lines(out + other)

    def requirement(self, ref):
        std, req = self.requirements.get(ref, ("", {}))
        if not req:
            return "", code(ref)
        return std, cell(f"{req.get('identifier', '')} {req.get('title', '')}".strip())


# ------------------------------------------------------------------ rows

def threat_rows(doc, ix, cats):
    t = doc.get("threats") or {}
    threats = t.get("threats") or []
    scenarios = t.get("threatScenarios") or []
    paths = t.get("attackPaths") or []
    patterns = {p["refId"]: p for p in t.get("attackPatterns") or [] if "refId" in p}
    weaknesses = {w["refId"]: w for w in (doc.get("definitions") or {}).get("weaknesses") or [] if "refId" in w}
    controls = {c["refId"]: c for c in doc.get("controls") or [] if "refId" in c}
    risks_doc = doc.get("risks") or {}
    damage = {d["refId"]: d for d in risks_doc.get("damageScenarios") or [] if "refId" in d}
    risks = risks_doc.get("risks") or []

    rows = []
    for th in threats:
        rid = th.get("refId", "")
        scen = [s for s in scenarios if rid in (s.get("threats") or [])]
        scen_ids = {s.get("refId") for s in scen}
        by_tax = {}
        for c in th.get("categories") or []:
            by_tax.setdefault(c.get("taxonomy"), []).append(words(c.get("category", "")))

        actors = []
        for s in scen:
            if s.get("actor") and ix.party_label(s["actor"]) not in actors:
                actors.append(ix.party_label(s["actor"]))
        origin = th.get("origin")
        actor = ", ".join(actors) or "-"
        if origin:
            actor = f"{actor} ({cell(origin)})" if actors else f"None ({cell(origin)})"

        impacts = [cell(v) for v in props(th, "lfai:nist-800-30:adverse-impact")]
        for s in scen:
            for d in s.get("damageScenarios") or []:
                if d in damage and damage[d].get("name"):
                    impacts.append("Damage: " + cell(damage[d]["name"]))

        nist30 = ([f"Source: {cell(v)}" for v in props(th, "lfai:nist-800-30:threat-source")]
                  + [f"Event: {cell(v)}" for v in props(th, "lfai:nist-800-30:threat-event")])

        items = props(th, "lfai:catalogue-item")
        cited = []
        for value in items:
            key, _, ident = value.partition(":")
            cited.append(cats.item(key, ident))

        techniques = list(props(th, "lfai:technique"))
        for p in paths:
            if rid in (p.get("realizes") or []):
                for step in p.get("steps") or []:
                    tid = (step.get("technique") or {}).get("id")
                    if tid and tid not in techniques:
                        techniques.append(tid)
        attack, atlas = [], []
        for tid in techniques:
            key, text = cats.technique(tid)
            (atlas if key == "mitre-atlas" else attack).append(text)
        tactics = by_tax.get("MITRE-ATTACK", [])
        mitre = []
        if tactics:
            mitre.append("ATT&amp;CK tactic: " + ", ".join(tactics))
        if attack:
            mitre.append("ATT&amp;CK: " + ", ".join(attack))
        if atlas:
            mitre.append("ATLAS: " + ", ".join(atlas))
        ai = bool(atlas) or any(v.partition(":")[0] in AI_CATALOGUES for v in items)

        rationale = {}
        for name in ("lfai:capec-rationale", "lfai:cwe-rationale"):
            for v in props(th, name):
                ident, _, why = v.partition(": ")
                rationale.setdefault(ident.strip(), []).append(why.strip())
        mech = []
        for ref in th.get("attackPatterns") or []:
            ap = patterns.get(ref, {})
            if "capecId" in ap:
                ident = f"CAPEC-{ap['capecId']}"
                text = link(f"{ident} {ap.get('name', '')}".strip(), CAPEC_URL.format(ap["capecId"]))
            else:
                ident, text = ref, code(ref)
            mech.append(text + "".join(f": {cell(w)}" for w in rationale.get(ident, [])))
        for w in th.get("weaknesses") or []:
            ref = w.get("ref") if isinstance(w, dict) else w
            wk = weaknesses.get(ref, {})
            cwes = [i.get("value") for i in wk.get("identifiers") or [] if i.get("scheme") == "cwe"]
            if not cwes:
                mech.append(cell(wk.get("name")) if wk.get("name") else code(ref))
            for ident in cwes:
                title, url = cats.items.get("cwe", {}).get(ident, (wk.get("name", ""), ""))
                mech.append(link(f"{ident} {title}".strip(), url)
                            + "".join(f": {cell(r)}" for r in rationale.get(ident, [])))

        mitigations = []
        for ref in th.get("mitigations") or []:
            c = controls.get(ref)
            mitigations.append(f"{cell(c['name'])} ({code(ref)})" if c and c.get("name") else code(ref))

        risk_text = []
        for r in risks:
            related = set(r.get("relatedThreats") or [])
            if rid not in related and not (scen_ids & related):
                continue
            inherent = r.get("inherentRisk") or {}
            lik = (inherent.get("likelihood") or {}).get("level")
            imp = [i.get("level") for i in inherent.get("impacts") or [] if i.get("level")]
            rating = []
            if lik:
                rating.append(f"likelihood {lik}")
            if imp:
                rating.append(f"impact {', '.join(imp)}")
            strategies = [x.get("strategy") for x in r.get("responses") or [] if x.get("strategy")]
            if strategies:
                rating.append(f"response {', '.join(strategies)}")
            text = cell(r.get("name") or r.get("refId", ""))
            risk_text.append(f"{text} ({cell('; '.join(rating))})" if lik or imp else f"{text} (unrated)")

        statement = th.get("description") or (scen[0].get("description") if scen else "")
        rows.append([
            code(rid),
            f"**{cell(th.get('name', ''))}**<br>{cell(statement)}" if th.get("name") else cell(statement),
            ", ".join(by_tax.get("STRIDE", [])) or "-",
            ", ".join(by_tax.get("MAESTRO", [])) or "-",
            ix.located_in(th.get("affects") or []),
            actor,
            lines(impacts),
            lines(nist30),
            lines(cited),
            lines(mitre),
            "Yes" if ai else "No",
            lines(mech),
            lines(mitigations),
            lines(risk_text),
        ])
    return rows


def control_rows(doc, ix):
    threats = (doc.get("threats") or {}).get("threats") or []
    rows = []
    for c in doc.get("controls") or []:
        rid = c.get("refId", "")
        reqs = {}
        for ref in c.get("satisfies") or []:
            std, text = ix.requirement(ref)
            reqs.setdefault(std, []).append(text)
        mitigates = [code(t["refId"]) for t in threats if rid in (t.get("mitigations") or [])]
        rows.append([
            code(rid),
            f"**{cell(c.get('name', ''))}**<br>{cell(c.get('description', ''))}",
            cell(c.get("category", "")) or "-",
            ", ".join(cell(v) for v in props(c, "lfai:control-tier")) or "-",
            cell(c.get("status", "")) or "-",
            lines([ix.name(r) for r in c.get("appliesTo") or []]),
            lines([f"{cell(std)}: {', '.join(texts)}" if std else ", ".join(texts) for std, texts in reqs.items()]),
            lines(mitigates),
        ])
    return rows


def not_applicable_rows(doc, refs, ix, cats):
    _, records, _ = tm_checks._not_applicable(doc, refs)
    grouped = {}
    for i, key, item, reason in records:
        grouped.setdefault(i, (reason, []))[1].append(cats.item(key, item))
    annotations = doc.get("annotations") or []
    return [[lines([ix.name(s) for s in annotations[i].get("subjects") or []]), lines(items), cell(reason)]
            for i, (reason, items) in grouped.items()]


# ------------------------------------------------------------------ page

def table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(out)


def render(doc, source_name, source_link=None):
    """The Markdown page. `source_link` is the TM-BOM's path relative to the page."""
    source_link = (source_link or source_name).replace(os.sep, "/").replace(" ", "%20")
    refs = tm_checks.References()
    cats = Catalogues(refs)
    ix = Index(doc)
    meta = doc.get("metadata") or {}
    uc_ref = next(iter(props(meta, "lfai:threat-model:use-case")), "")
    uc_name = ix.names.get(uc_ref, uc_ref) or "threat model"
    system = next(iter(props(meta, "lfai:threat-model:system-bom")), "")
    methods = [m if isinstance(m, str) else m.get("name", "") for m in (doc.get("threats") or {}).get("methodologies") or []]

    t_rows = threat_rows(doc, ix, cats)
    c_rows = control_rows(doc, ix)
    n_rows = not_applicable_rows(doc, refs, ix, cats)
    stride = {}
    for th in (doc.get("threats") or {}).get("threats") or []:
        for c in th.get("categories") or []:
            if c.get("taxonomy") == "STRIDE":
                stride[words(c.get("category", ""))] = stride.get(words(c.get("category", "")), 0) + 1

    out = [
        f"<!-- {GENERATOR} from {source_name}. Do not edit: change the TM-BOM and regenerate. -->",
        "",
        f"# Threat model: {cell(uc_name)}",
        "",
        f"Generated from the CycloneDX 2.0 threat-model BOM [{cell(source_name)}]({source_link}). "
        "The TM-BOM is the source of truth: to change this page, change the TM-BOM and run "
        "`.bob/skills/cyclonedx/scripts/tm_to_markdown.py` again.",
        "",
        "| | |",
        "|---|---|",
        f"| Use case | {code(uc_ref) if uc_ref else '-'} |",
        f"| TM-BOM | {code(doc.get('serialNumber', '-'))}, version {cell(doc.get('version', '-'))}, "
        f"{cell(meta.get('timestamp', ''))} |",
        f"| System BOM | {code(system) if system else '-'} |",
        f"| Methodologies | {cell(', '.join(methods)) or '-'} |",
        f"| Threats | {len(t_rows)} |",
        f"| Threats per STRIDE category | {', '.join(f'{k}: {v}' for k, v in sorted(stride.items())) or '-'} |",
        f"| Controls | {len(c_rows)} |",
        f"| Not-applicable decisions | {len(n_rows)} |",
        "",
        "## Threats",
        "",
        "\"AI specific?\" is Yes when the threat cites a MITRE ATLAS technique or an OWASP Top 10 for LLM "
        "or Agentic Applications item. A threat can have several STRIDE categories. `validate_bom.py` "
        "checks every CAPEC, CWE, ATT&amp;CK, ATLAS and NIST ID against its reference file; this page "
        "does not, so validate the TM-BOM before sharing it.",
        "",
        table(["ID", "Threat Scenario", "STRIDE", "MAESTRO", "Located In", "Actor",
               "Impact / Compromised Asset", "NIST SP 800-30 Source and Event", "Catalogue Items",
               "MITRE ATT&amp;CK and ATLAS", "AI specific?", "Mechanism of Attack (CAPEC) and Weakness (CWE)",
               "Mitigating Controls", "Risk"], t_rows) if t_rows else "No threats.",
        "",
        "## Controls",
        "",
        table(["ID", "Control", "Category", "Tier", "Status", "Applies To", "Requirements", "Mitigates"],
              c_rows) if c_rows else "No controls.",
        "",
        "## Catalogue items decided not applicable",
        "",
        "Each catalogue sweep item that was decided not to apply to an element, with the reason. "
        "The validator checks that a reason was given, not that it is sound: review these.",
        "",
        table(["Elements", "Catalogue Items", "Reason"], n_rows) if n_rows else "None recorded.",
        "",
    ]
    return "\n".join(out)


def default_output(path):
    return (path[:-5] if path.lower().endswith(".json") else path) + ".threats.md"


def write(path, text):
    if os.path.exists(path):
        with open(path, encoding="utf-8", errors="replace") as f:
            head = f.read(500)
        if GENERATOR not in head:
            sys.exit(f"{path} exists and was not written by this tool; choose another -o")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("tm_bom", help="threat-model BOM (CycloneDX 2.0 JSON)")
    p.add_argument("-o", "--output", help="output Markdown file, or '-' for stdout "
                                          "(default: the TM-BOM path with .json replaced by .threats.md)")
    args = p.parse_args(argv)
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")

    with open(args.tm_bom, encoding="utf-8") as f:
        doc = json.load(f)
    if doc.get("specFormat") != "CycloneDX" or str(doc.get("specVersion")) != "2.0":
        sys.exit(f"{args.tm_bom}: not a CycloneDX 2.0 document (specFormat 'CycloneDX', specVersion '2.0')")
    if not tm_checks.is_threat_model(doc):
        sys.exit(f"{args.tm_bom}: not a threat-model BOM (no threats, and no lfai:threat-model:use-case property)")

    out = args.output or default_output(args.tm_bom)
    name = os.path.basename(args.tm_bom)
    if out == "-":
        sys.stdout.write(render(doc, name))
        return 0
    rel = os.path.relpath(os.path.abspath(args.tm_bom), os.path.dirname(os.path.abspath(out)))
    write(out, render(doc, name, rel))
    t = doc.get("threats") or {}
    print(f"wrote {out}: {len(t.get('threats') or [])} threats, {len(doc.get('controls') or [])} controls, "
          f"{len(tm_checks._not_applicable(doc, tm_checks.References())[1])} not-applicable decisions")
    return 0


if __name__ == "__main__":
    sys.exit(main())
